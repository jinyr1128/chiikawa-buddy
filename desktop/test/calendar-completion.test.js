import assert from 'node:assert/strict';
import {Store} from '../../agent/src/store.ts';
import {calendarCompletion} from '../src/calendar-completion.js';
import {eventWhen} from '../src/calendar-tab.js';
const store=new Store(':memory:'),db=store.db;
const at=(s)=>Date.parse('2026-11-24T'+s+':00+09:00'),iso=s=>new Date(at(s)).toISOString();
const ev=(id,title,s='11:00',e='12:00',extras={})=>({id,calId:'k',title,start:iso(s),end:iso(e),...extras});
const first=ev('k:meeting#1','정기 회의'),later=ev('k:meeting#2','정기 회의','14:00','15:00');
let events=[first,later,ev('k:prep','정기 회의 준비'),ev('k:all','전체 회의','11:00','12:00',{allDay:true}),ev('k:no','영업 회의','11:00','12:00',{response:'declined'}),ev('k:free','팀 회의','11:00','12:00',{free:true})];
let failed=false,freshSwitch=null;
const request=async(_,url)=>{
 if(freshSwitch && url.includes('fresh=1')){freshSwitch();freshSwitch=null;}
 return {ok:true,data:{ok:!failed,connected:true,mode:'api',calendars:[{id:'k',name:'회사',enabled:true,phase:failed?'failed':'ok'}],events}};
};
const run=s=>calendarCompletion(db,request,{now:at(s)});
const follow=store.addTodo({title:'회의록 공유',priority:1});
const desc='일정: '+eventWhen({s:at('11:00'),e:at('12:00')},'Asia/Seoul')+'\n캘린더: 회사';
const existing=store.addTodo({title:first.title,description:desc,priority:1});
db.prepare('UPDATE todos SET created=? WHERE id=?').run(iso('08:00'),existing.id);
await run('10:00');
assert.equal(store.openTodos().length,3);
const second=store.openTodos().find(t=>t.id.startsWith('cal:')).id;
await calendarCompletion(db,request,{now:at('11:30'),pin:{id:first.id,start:at('11:00')}});
assert.equal(store.openTodos().length,3);
await run('11:59');assert.equal(store.getTodo(existing.id).status,'open');
freshSwitch=()=>events[0]={...first,end:iso('12:30')};
await run('12:00');assert.equal(store.getTodo(existing.id).status,'open');
await run('12:30');assert.equal(store.getTodo(existing.id).doneBy,'auto');
assert.equal(store.getTodo(existing.id).updated,iso('12:30'));
assert.equal(store.getTodo(follow.id).status,'open');assert.equal(store.getTodo(second).status,'open');
const checked=()=>store.ledgerForDay('2026-11-24').filter(e=>e.by==='auto' && e.action==='done');
await run('12:31');assert.equal(checked().length,1);
store.revertAutoTodo(existing.id);await run('12:32');assert.equal(store.getTodo(existing.id).status,'open');
events=events.filter(e=>e.id!==later.id);failed=true;await run('14:00');assert.equal(store.getTodo(second).status,'open');
failed=false;await run('14:01');assert.ok(store.trashedTodo(second));assert.equal(checked().length,1);
events.push(later);await run('14:02');assert.equal(store.getTodo(second).status,'open');
await calendarCompletion(db,request,{now:at('15:00')+86400000});
assert.equal(store.getTodo(second).updated,iso('15:00'));assert.equal(checked().length,2);
assert.equal(store.getTodo(follow.id).status,'open');assert.equal(store.getTodo(existing.id).status,'open');
db.close();
